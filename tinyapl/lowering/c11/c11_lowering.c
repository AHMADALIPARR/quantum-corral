#include "c11_lowering.h"
#include <string.h>

static void emit_expr_loop(const IrNode *n, const char *dst, FILE *out, int indent) {
    if (!n) return;
    if (n->op == IR_OP_MAG2 && n->lhs && n->lhs->op == IR_OP_VAR && n->rank == 2) {
        /* Direct lowering to shared C11/Fortran ABI kernel corral_density */
        fprintf(out, "%*scorral_density(%s_re, %s_im, %s, (int)nx, (int)ny);\n",
                indent, "", n->lhs->name, n->lhs->name, dst);
        return;
    }

    if (n->op == IR_OP_REDUCE_SUM && n->lhs) {
        fprintf(out, "%*sdouble %s = corral_total_probability(%s, (int)nx, (int)ny, dx, dy);\n",
                indent, "", dst, n->lhs->name);
        return;
    }

    if (n->op == IR_OP_ADD && n->rank == 2) {
        fprintf(out, "%*sfor (int64_t i = 0; i < nx * ny; ++i) {\n", indent, "");
        fprintf(out, "%*s    %s[i] = %s[i] + %s[i];\n", indent, "", dst, n->lhs->name, n->rhs->name);
        fprintf(out, "%*s}\n", indent, "");
        return;
    }

    if (n->op == IR_OP_MUL && n->rank == 2 && n->lhs->rank == 0) {
        fprintf(out, "%*sfor (int64_t i = 0; i < nx * ny; ++i) {\n", indent, "");
        fprintf(out, "%*s    %s[i] = %.15g * %s[i];\n", indent, "", dst, n->lhs->scalar_val, n->rhs->name);
        fprintf(out, "%*s}\n", indent, "");
        return;
    }

    fprintf(out, "%*s/* Lowered op %d for %s */\n", indent, "", (int)n->op, dst);
}

int tinyapl_lower_to_c11(const IrNode *prog, FILE *out) {
    if (!prog || !out) return -1;

    fprintf(out, "/* Auto-generated by tinyaplc (tinyAPL -> C11 Lowering Backend) */\n");
    fprintf(out, "#include \"corral.h\"\n");
    fprintf(out, "#include <math.h>\n");
    fprintf(out, "#include <stdint.h>\n\n");
    fprintf(out, "int tinyapl_corral_eval(const double *psi_re, const double *psi_im,\n");
    fprintf(out, "                        double *rho_out, double *total_prob_out,\n");
    fprintf(out, "                        int64_t nx, int64_t ny, double dx, double dy) {\n");
    fprintf(out, "    int64_t shape2[2] = { nx, ny };\n");
    fprintf(out, "    CorralArray rho_arr = corral_array_alloc(2, shape2, CORRAL_F64, CORRAL_LAYOUT_ROW_MAJOR);\n");
    fprintf(out, "    double *rho = (double *)rho_arr.data;\n");
    fprintf(out, "    if (!rho) return -1;\n\n");

    for (const IrNode *stmt = prog; stmt != NULL; stmt = stmt->next) {
        if (stmt->op == IR_OP_ASSIGN) {
            if (strcmp(stmt->name, "rho") == 0) {
                emit_expr_loop(stmt->lhs, "rho", out, 4);
            } else {
                emit_expr_loop(stmt->lhs, stmt->name, out, 4);
                if (stmt->rank == 0 && strcmp(stmt->name, "P") == 0) {
                    fprintf(out, "    if (total_prob_out) *total_prob_out = P;\n");
                }
            }
        }
    }

    fprintf(out, "\n    for (int64_t i = 0; i < nx * ny; ++i) rho_out[i] = rho[i];\n");
    fprintf(out, "    corral_array_free(&rho_arr);\n");
    fprintf(out, "    return 0;\n");
    fprintf(out, "}\n");
    return 0;
}
